def get_control_points():
    """Возвращает 22 опорные точки для составной кривой.
    Специально подобраны так, чтобы:
    1. Образовать самопересекающуюся фигуру (восьмерку/петли).
    2. В стыках (6, 12, 18) соблюдалась коллинеарность для G1-гладкости.
    Коллинеарность означает, что векторы (P_5 -> P_6) и (P_6 -> P_7) 
    лежат на одной прямой, поэтому касательные совпадают."""
    return [
        # Сегмент 1 (индексы 0-6): правая петля вниз
        ( 0.0,  0.0),  # 0
        ( 1.0,  2.0),  # 1
        ( 2.0,  3.0),  # 2
        ( 3.0,  2.0),  # 3
        ( 2.0,  1.0),  # 4
        ( 1.0,  0.0),  # 5
        ( 0.0, -1.0),  # 6 (СТЫК 1: точки 5, 6, 7 лежат на одной прямой)
        
        # Сегмент 2 (индексы 6-12): левая петля вверх
        (-1.0, -2.0),  # 7 (продолжает прямую 5-6)
        (-2.0, -3.0),  # 8
        (-3.0, -2.0),  # 9
        (-2.0, -1.0),  # 10
        (-1.0,  1.0),  # 11
        ( 0.0,  2.0),  # 12 (СТЫК 2: точки 11, 12, 13 лежат на одной прямой)
        
        # Сегмент 3 (индексы 12-18): правая петля вниз (с самопересечением)
        ( 1.0,  3.0),  # 13 (продолжает прямую 11-12)
        ( 2.0,  2.0),  # 14
        ( 3.0,  0.0),  # 15
        ( 2.0, -2.0),  # 16
        ( 1.0, -2.0),  # 17
        ( 0.0, -2.0),  # 18 (СТЫК 3: точки 17, 18, 19 лежат на одной прямой)
        
        # Сегмент 4 (индексы 18-21): левая петля вверх (степень 3)
        (-1.0, -2.0),  # 19 (продолжает прямую 17-18)
        (-2.0, -1.0),  # 20
        (-1.0,  0.0),  # 21
    ]


