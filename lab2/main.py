# ЧАСТЬ 3. ПОСТРОЕНИЕ СОСТАВНОЙ КРИВОЙ
# =============================================================

def build_composite_bezier(points, degree=6, steps=100):
    """Строит составную кривую Безье заданной степени.
    Возвращает списки X и Y для отрисовки единой линии."""
    curve_x = []
    curve_y = []
    
    # Проходим по точкам, отрезая сегменты по (degree + 1) штук
    start_idx = 0
    while start_idx < len(points) - 1:
        # Определяем конец текущего сегмента
        end_idx = start_idx + degree + 1
        
        # Если оставшихся точек меньше, берем сколько есть (понижаем степень)
        if end_idx > len(points):
            end_idx = len(points)
        
        # Выделяем контрольные точки текущего сегмента
        segment = points[start_idx:end_idx]
        
        # Степень текущего сегмента (на 1 меньше числа точек)
        current_degree = len(segment) - 1
        
        # Генерируем точки кривой для этого сегмента
        for i in range(steps + 1):
            t = i / steps  # t от 0 до 1
            
            # Если это не первый сегмент и t = 0, пропускаем точку,
            # так как она совпадает с концом предыдущего сегмента
            if start_idx > 0 and i == 0:
                continue
                
            x, y = bezier_point(segment, t)
            curve_x.append(x)
            curve_y.append(y)
        
        # Следующий сегмент начинается с последней точки текущего
        start_idx = end_idx - 1
        
    return curve_x, curve_y


