def factorial(n):
    """Вычисление факториала n! без использования math.factorial.
    Формула: n! = 1 * 2 * 3 * ... * n.
    Итеративный подход для наглядности."""
    result = 1  # Начинаем с 1, так как 0! = 1 и 1! = 1
    for i in range(2, n + 1):  # Идем от 2 до n включительно
        result *= i            # Накапливаем произведение: result = result * i
    return result              # Возвращаем итоговое значение факториала


def binomial_coefficient(n, i):
    """Биномиальный коэффициент C_n^i (из n по i).
    Формула: C_n^i = n! / (i! * (n-i)!)."""
    # Проверка на некорректный индекс (защита от ошибок)
    if i < 0 or i > n:
        return 0
    # Считаем по формуле, используя нашу функцию factorial.
    # Двойной слэш // означает целочисленное деление (результат всегда целый).
    return factorial(n) // (factorial(i) * factorial(n - i))


def bernstein_polynomial(i, n, t):
    """Полином Бернштейна B_i^n(t). Это "вес" (влияние) i-й точки на кривую.
    Формула: B_i^n(t) = C_n^i * t^i * (1-t)^(n-i)."""
    return (binomial_coefficient(n, i) *  # Берем биномиальный коэффициент C_n^i
            (t ** i) *                    # Умножаем на t в степени i
            ((1 - t) ** (n - i)))         # Умножаем на (1-t) в степени (n-i)


def bezier_point(control_points, t):
    """Вычисление координат ОДНОЙ точки на кривой Безье для заданного t.
    Формула: P(t) = Сумма (от i=0 до n) [ B_i^n(t) * P_i ].
    control_points — список кортежей (x, y).
    t — параметр от 0 до 1.
    Возвращает кортеж (x, y)."""
    n = len(control_points) - 1  # Степень полинома = число точек минус 1
    x = 0.0                      # Начальная сумма координаты X
    y = 0.0                      # Начальная сумма координаты Y
    
    # Перебираем все опорные точки (px, py) с их индексами i
    for i, (px, py) in enumerate(control_points):
        b = bernstein_polynomial(i, n, t)  # Считаем вес Бернштейна для этой точки в момент t
        x += b * px                        # Прибавляем к X: (вес * координата_x_точки)
        y += b * py                        # Прибавляем к Y: (вес * координата_y_точки)
        
    return (x, y)  # Возвращаем координаты готовой точки на кривой


def de_casteljau(control_points, t):
    """Альтернативный алгоритм вычисления (метод де Кастельжа).
    Обладает лучшей численной устойчивостью (без вычисления факториалов).
    Формула: P_i^r = (1-t)*P_i^{r-1} + t*P_{i+1}^{r-1}."""
    pts = list(control_points)  # Делаем копию списка точек, чтобы не менять исходный
    n = len(pts)                # Количество точек
    
    # Выполняем n-1 итераций схождения (пока не останется 1 точка)
    for r in range(1, n):
        new_pts = []            # Список для точек следующего уровня
        for i in range(n - r):  # Количество новых точек уменьшается на 1 на каждом шаге
            # Вычисляем координаты новой точки по формуле линейной интерполяции
            x = (1 - t) * pts[i][0] + t * pts[i + 1][0]
            y = (1 - t) * pts[i][1] + t * pts[i + 1][1]
            new_pts.append((x, y))  # Добавляем новую точку
        pts = new_pts               # Переходим на следующий уровень
    return pts[0]  # Возвращаем единственную оставшуюся точку — это и есть точка на кривой


