def plot_bezier(points, curve_x, curve_y, filename):
    """Рисует опорный полигон, опорные точки и саму кривую."""
    fig, ax = plt.subplots(figsize=(10, 10))  # Создаем фигуру 10x10 дюймов
    
    # 1. Рисуем серую ломаную (опорный полигон), чтобы видеть наши 22 точки
    poly_x = [p[0] for p in points]  # Извлекаем все X из списка точек
    poly_y = [p[1] for p in points]  # Извлекаем все Y из списка точек
    ax.plot(poly_x, poly_y, 'o--', color='gray', alpha=0.6, 
            label='Опорный полигон (22 точки)')
    
    # 2. Выделяем стыки сегментов крупными красными квадратами (точки 6, 12, 18)
    joints = [6, 12, 18]  # Индексы точек стыка
    for j in joints:
        ax.plot(points[j][0], points[j][1], 's', color='red', markersize=8,
                label='Стыки сегментов (G1)' if j == 6 else "")  # Подпись только для первой

    # 3. Рисуем саму синюю кривую Безье
    ax.plot(curve_x, curve_y, '-', color='blue', linewidth=2.5, 
            label='Составная кривая Безье')
    
    # 4. Настройка осей и оформления
    ax.set_aspect('equal')  # Одинаковый масштаб по X и Y (чтобы круги не были овалами)
    ax.grid(True, linestyle='--', alpha=0.5)  # Пунктирная сетка
    ax.axhline(0, color='black', linewidth=1) # Ось X
    ax.axvline(0, color='black', linewidth=1) # Ось Y
    
    ax.set_title("Самопересекающаяся составная кривая Безье 6-й степени\n(22 опорные точки)", fontsize=14)
    ax.set_xlabel("X")  # Подпись оси X
    ax.set_ylabel("Y")  # Подпись оси Y
    ax.legend(loc='upper right')  # Показываем легенду в правом верхнем углу
    
    # 5. Сохранение и закрытие
    plt.tight_layout()  # Автоматически подгоняем отступы, чтобы ничего не обрезалось
    fig.savefig(filename, dpi=150, bbox_inches='tight')  # Сохраняем в файл
    plt.close(fig)  # Закрываем фигуру, чтобы освободить память


