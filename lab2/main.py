def plot_bezier(points, curve_x, curve_y, filename):
    """Рисует опорный полигон, опорные точки и саму кривую."""
    fig, ax = plt.subplots(figsize=(10, 10))
    
    # 1. Рисуем опорный полигон (соединяем точки линиями)
    poly_x = [p[0] for p in points]
    poly_y = [p[1] for p in points]
    ax.plot(poly_x, poly_y, 'o--', color='gray', alpha=0.6, 
            label='Опорный полигон (22 точки)')
    
    # 2. Выделяем стыки сегментов крупными маркерами
    joints = [6, 12, 18]
    for j in joints:
        ax.plot(points[j][0], points[j][1], 's', color='red', markersize=8,
                label='Стыки сегментов (G1)' if j == 6 else "")

    # 3. Рисуем саму кривую Безье
    ax.plot(curve_x, curve_y, '-', color='blue', linewidth=2.5, 
            label='Составная кривая Безье')
    
    # 4. Настройка осей и оформления
    ax.set_aspect('equal')  # Одинаковый масштаб по X и Y
    ax.grid(True, linestyle='--', alpha=0.5)
    ax.axhline(0, color='black', linewidth=1)
    ax.axvline(0, color='black', linewidth=1)
    
    ax.set_title("Самопересекающаяся составная кривая Безье 6-й степени\n(22 опорные точки)", fontsize=14)
    ax.set_xlabel("X")
    ax.set_ylabel("Y")
    ax.legend(loc='upper right')
    
    # 5. Сохранение и показ
    plt.tight_layout()
    fig.savefig(filename, dpi=150, bbox_inches='tight')
    plt.close(fig)


