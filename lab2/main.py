# ЧАСТЬ 3. ПОСТРОЕНИЕ СОСТАВНОЙ КРИВОЙ
# =============================================================

def build_composite_bezier(points, degree=6, steps=100):
    """Строит составную кривую Безье, нарезая 22 точки на сегменты.
    Возвращает списки X и Y для отрисовки единой линии."""
    curve_x = []  # Сюда будем собирать все X для рисования
    curve_y = []  # Сюда будем собирать все Y для рисования
    
    start_idx = 0  # Индекс, с которого начинается текущий сегмент
    
    # Запускаем цикл, пока не пройдем все точки (22 штуки)
    while start_idx < len(points) - 1:
        # Определяем конец текущего сегмента: degree + 1 точек (для 6-й степени это 7 точек)
        end_idx = start_idx + degree + 1
        
        # Если оставшихся точек меньше, берем сколько есть (понижаем степень для хвоста)
        if end_idx > len(points):
            end_idx = len(points)
        
        # Выделяем контрольные точки текущего сегмента (срез списка)
        segment = points[start_idx:end_idx]
        
        # Степень текущего сегмента (на 1 меньше числа точек)
        current_degree = len(segment) - 1
        
        # Генерируем точки кривой для этого сегмента (разбиваем на steps шагов)
        for i in range(steps + 1):
            t = i / steps  # Параметр t плавно меняется от 0.0 до 1.0
            
            # Если это не первый сегмент и t = 0, пропускаем точку,
            # так как она совпадает с последней точкой предыдущего сегмента (избегаем дублей)
            if start_idx > 0 and i == 0:
                continue
                
            # Считаем координаты точки для текущего t и добавляем в общий список
            x, y = bezier_point(segment, t)
            curve_x.append(x)
            curve_y.append(y)
        
        # Следующий сегмент начинается с последней точки текущего (для сшивки)
        start_idx = end_idx - 1
        
    return curve_x, curve_y


